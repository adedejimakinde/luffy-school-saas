# Question banks, their questions, and tests (`docs/cbt.md`, Phase 2 step 3). The rules
# that keep a set test as it was live here, in the database, as triggers named for them
# (`docs/operating-rules.md` rule 3):
#
# - a set test keeps its paper: once it leaves draft, its window, time, settings and
#   sign-in never change, and it moves only along draft -> submitted -> published ->
#   closed (or back from submitted to draft); it is never deleted;
# - a published item is frozen: a test's copied question is never updated, and is
#   added or removed only while its test is a draft; its answer is one of its options;
# - a set test's section is fixed: where its questions come from, and how many;
# - a test's state changes and its audience changes are append-only;
# - a provider's question is read-only (none exists yet; the provider is designed and off).
#
# No question is written by this migration, or any other (`cbt/tests` asserts it).
#
