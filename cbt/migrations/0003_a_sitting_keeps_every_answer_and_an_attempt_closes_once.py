# code changes. The rules live here, as triggers named for them (operating rule 3):
#
# - every answer is kept: an answer event is never updated or deleted, so the answer that
#   lost is still there beside the one that counted;
# - the sitting log, extra time, retakes, sitting controls and code changes are
#   append-only;
# - an attempt is closed once: `submitted_at` and `ended_by` go from empty to set, once,
#   and nothing else of the row ever changes; it is never deleted;
# - a session is ended once: likewise `ended_at` and `ended_by`; only `last_seen_at`, the
#   heartbeat, moves while it is open. The partial unique index
#   `one_computer_holds_an_attempt` keeps one open session per attempt.
