"""The report card snapshot, and the row that says a card went home.

Three new tables, and a nullable `card` column on the three that already froze
a *section* of a card. `0017` backfills that column and makes it NOT NULL;
`0018` makes all three new tables append-only.

## `ReleasedCard` is the artefact

One row per child per release, written **unconditionally** — no marks, no
ratings, the conduct section off school-wide, nothing decided. Before it, "has a
card gone home for this child?" had four places to look and a placement join to
fall back on, and the fallback answered a different question: `ClassPlacement`
holds one group per child per term, so a mid-term move rewrites the row and the
record of where the child sat at release is destroyed rather than superseded.
That is what let a released remark be rewritten for a moved child, which `0010`
and `0011` fixed one table at a time. Issues #31, #33 and #34 each arrived here
from a different direction.

**No constraint in this migration holds that guarantee**, and none can: no
`CHECK` can say "a row exists for every child on a roster this transaction has
already moved past". It is held by `results.cards.freeze_for_release()` and
pinned by a test with a control behind it.

## The `card` column is nullable here and not later

Added nullable so that `0017` has somewhere to write the backfill before
tightening it. Splitting the three steps — schema, data, constraint — is what
lets each one be read and reverted on its own.
"""

