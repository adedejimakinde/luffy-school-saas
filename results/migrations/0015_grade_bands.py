"""The grading scale a school starts from, and the shape that makes it safe.

`GradeBand` stores where a band *starts* and nothing else — a band runs up to
the next band's `minimum`, and the top band runs to 100. The model docstring has
the argument; the short version is that "bands neither overlap nor leave gaps"
is two invariants that row-level `CHECK`s cannot both express, and this shape
makes both unrepresentable instead of merely checked.

What is left is coverage — is there a band at nought? — which is a fact about
the table rather than about a row, and lives in `grades.set_scale()`.

## The seed

The WAEC nine-point scale, which is what most Nigerian secondary schools start
from:

    A1  75-100  Excellent      C6  50-54  Credit
    B2  70-74   Very Good      D7  45-49  Pass
    B3  65-69   Good           E8  40-44  Pass
    C4  60-64   Credit         F9   0-39  Fail
    C5  55-59   Credit

**A seed is a starting point and not a promise.** Every row is editable, nothing
in the code names a band, and a school that grades differently replaces the lot
through `grades.set_scale()`. The band *values* here are the ones flagged for
confirmation in this PR's body — seed data is cheap to change and schema is not,
so the schema did not wait on them.

Seeded per schema, the way `0006` seeds traits and `0013` seeds the session
settings row. A schema created around this migration still reads correctly:
`grades.scale()` returns an empty list and `grade_for()` returns `None`, so a
card prints no letter rather than failing.
"""

